const iconMap = {
  github: GitHubIcon,
  linkedin: LinkedInIcon,
  mail: MailIcon,
  discord: DiscordIcon,
  roblox: RobloxIcon,
} as const;

interface IconLinkProps {
  label: string;
  href?: string;
  icon: keyof typeof iconMap;
  copyable?: boolean;
  copyText?: string;
  copyOnly?: boolean;
  displayLabel?: string;
  size?: number;
}

export function IconLink({
  label,
  href,
  icon,
  copyable = false,
  copyText,
  copyOnly = false,
  displayLabel,
  size = 20,
}: IconLinkProps) {
  const [copied, setCopied] = useState(false);
  const Icon = iconMap[icon];
  const textToCopy = copyText ?? href?.replace("mailto:", "") ?? "";

  const handleCopy = async () => {
    try {
      await navigator.clipboard.writeText(textToCopy);
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    } catch {
      setCopied(false);
    }
  };

  const shownLabel =
    copied && copyable
      ? "Copied"
      : displayLabel ?? (copyOnly && copyText ? copyText : label);

  const iconEl = (
    <Icon
      width={size}
      height={size}
      className="text-foreground/60 transition-colors group-hover:text-foreground"
    />
  );

  const labelEl = (
    <span className="text-sm text-muted transition-colors group-hover:text-link">
      {shownLabel}
    </span>
  );

  if (copyOnly || (copyable && !href)) {
    return (
      <button
        type="button"
        onClick={handleCopy}
        className="group flex items-center gap-2.5 transition-colors"
        aria-label={`Copy ${label}`}
      >
        {iconEl}
        {labelEl}
      </button>
    );
  }

  if (copyable && href) {
    return (
      <div className="flex items-center gap-3">
        <a
          href={href}
          className="group flex items-center gap-2.5 transition-colors"
          aria-label={label}
        >
          {iconEl}
          <span className="text-sm text-muted transition-colors group-hover:text-link">
            {label}
          </span>
        </a>
        <button
          type="button"
          onClick={handleCopy}
          className="text-xs text-muted/70 transition-colors hover:text-link"
          aria-label={`Copy ${textToCopy}`}
        >
          {copied ? "Copied" : "Copy"}
        </button>
      </div>
    );
  }

  return (
    <a
      href={href}
      target={href?.startsWith("http") ? "_blank" : undefined}
      rel={href?.startsWith("http") ? "noopener noreferrer" : undefined}
      className="group flex items-center gap-2.5 transition-colors"
      aria-label={label}
    >
      {iconEl}
      {labelEl}
    </a>
  );
}
